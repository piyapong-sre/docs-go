// ตัวอย่าง code generation แบบ stringer ย่อส่วน:
// อ่าน source ด้วย go/parser + go/ast -> สร้างโค้ดด้วย text/template -> จัดรูปด้วย go/format
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"text/template"
)

// source คือไฟล์ Go ที่เราต้องการ generate String() ให้
// (ของจริงจะอ่านจากไฟล์ใน package ด้วย parser.ParseFile(fset, "color.go", nil, 0))
const source = `package paint

type Color int

const (
	Red Color = iota
	Green
	Blue
)
`

// tmpl คือแม่แบบของโค้ดที่จะสร้าง
var tmpl = template.Must(template.New("stringer").Parse(`// Code generated by codegen; DO NOT EDIT.

package {{.Package}}

import "strconv"

func (v {{.Type}}) String() string {
	switch v {
	{{- range .Names}}
	case {{.}}:
		return "{{.}}"
	{{- end}}
	}
	return "{{.Type}}(" + strconv.Itoa(int(v)) + ")"
}
`))

type data struct {
	Package string
	Type    string
	Names   []string
}

// findConsts หาชื่อ const ทั้งหมดที่เป็นชนิด typeName (รองรับรูปแบบ iota)
func findConsts(file *ast.File, typeName string) []string {
	var names []string
	ast.Inspect(file, func(n ast.Node) bool {
		decl, ok := n.(*ast.GenDecl)
		if !ok || decl.Tok != token.CONST {
			return true
		}
		current := "" // ชนิดของบรรทัดก่อนหน้า (บรรทัดที่ละ type ไว้จะใช้ชนิดเดิม)
		for _, spec := range decl.Specs {
			vs := spec.(*ast.ValueSpec)
			if ident, ok := vs.Type.(*ast.Ident); ok {
				current = ident.Name
			} else if vs.Type != nil || len(vs.Values) > 0 {
				current = ""
			}
			if current == typeName {
				for _, name := range vs.Names {
					names = append(names, name.Name)
				}
			}
		}
		return false
	})
	return names
}

func main() {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "color.go", source, parser.ParseComments)
	if err != nil {
		panic(err)
	}

	d := data{Package: file.Name.Name, Type: "Color", Names: findConsts(file, "Color")}
	fmt.Printf("พบ const ของ %s: %v\n\n", d.Type, d.Names)

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, d); err != nil {
		panic(err)
	}

	// go/format ทำให้ผลลัพธ์เหมือนผ่าน gofmt และช่วยจับ syntax error ของโค้ดที่ generate
	out, err := format.Source(buf.Bytes())
	if err != nil {
		panic(err)
	}
	fmt.Print(string(out))
}
